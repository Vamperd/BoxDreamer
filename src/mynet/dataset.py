from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np
import torch
from PIL import Image
from torch.utils.data import Dataset


IMAGENET_MEAN = torch.tensor([0.485, 0.456, 0.406], dtype=torch.float32).view(3, 1, 1)
IMAGENET_STD = torch.tensor([0.229, 0.224, 0.225], dtype=torch.float32).view(3, 1, 1)


def _load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def resolve_path(path_value: Optional[str], *, index_path: Path, dataset_root: Optional[Path]) -> Optional[Path]:
    if path_value is None:
        return None

    raw = Path(path_value)
    candidates: List[Path] = []
    if raw.is_absolute():
        candidates.append(raw)
    else:
        if dataset_root is not None:
            candidates.append(dataset_root / raw)
            candidates.append(dataset_root / raw.name)
        candidates.append(Path.cwd() / raw)
        candidates.append(index_path.parent / raw)
        candidates.append(index_path.parent / raw.name)

    for candidate in candidates:
        if candidate.exists():
            return candidate

    return candidates[0] if candidates else raw


class BOPCornerDataset(Dataset):
    """Dataset for MyNet JSON files generated by scripts/build_mynet_dataset.py."""

    def __init__(
        self,
        index_path: str | Path,
        dataset_root: str | Path | None = None,
        normalize: bool = True,
    ) -> None:
        self.index_path = Path(index_path)
        self.dataset_root = Path(dataset_root) if dataset_root is not None else None
        self.samples: List[Dict[str, Any]] = _load_json(self.index_path)
        self.normalize = normalize

        if not isinstance(self.samples, list):
            raise ValueError(f"Index must contain a list of samples: {self.index_path}")

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        sample = self.samples[idx]
        crop_path = resolve_path(sample["crop_path"], index_path=self.index_path, dataset_root=self.dataset_root)
        heatmap_path = resolve_path(sample["heatmap_path"], index_path=self.index_path, dataset_root=self.dataset_root)
        if crop_path is None or heatmap_path is None:
            raise FileNotFoundError(f"Missing crop or heatmap path for sample {sample.get('sample_id', idx)}")

        image_np = np.asarray(Image.open(crop_path).convert("RGB"), dtype=np.float32) / 255.0
        image = torch.from_numpy(image_np).permute(2, 0, 1).contiguous()
        if self.normalize:
            image = (image - IMAGENET_MEAN) / IMAGENET_STD

        heatmap_np = np.load(heatmap_path).astype(np.float32)
        heatmap = torch.from_numpy(heatmap_np)

        return {
            "image": image,
            "heatmap": heatmap,
            "corners_2d_crop": torch.tensor(sample["corners_2d_crop"], dtype=torch.float32),
            "corner_valid": torch.tensor(sample["corner_valid"], dtype=torch.bool),
            "crop_box_xyxy_full": torch.tensor(sample["crop_box_xyxy_full"], dtype=torch.float32),
            "K": torch.tensor(sample["K"], dtype=torch.float32),
            "R": torch.tensor(sample["R"], dtype=torch.float32),
            "t": torch.tensor(sample["t"], dtype=torch.float32),
            "sample_id": sample["sample_id"],
        }


def collate_corner_batch(batch: List[Dict[str, Any]]) -> Dict[str, Any]:
    tensor_keys = [
        "image",
        "heatmap",
        "corners_2d_crop",
        "corner_valid",
        "crop_box_xyxy_full",
        "K",
        "R",
        "t",
    ]
    out: Dict[str, Any] = {key: torch.stack([item[key] for item in batch], dim=0) for key in tensor_keys}
    out["sample_id"] = [item["sample_id"] for item in batch]
    return out


from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

import numpy as np
import torch
from PIL import Image
from torch.utils.data import Dataset


IMAGENET_MEAN = torch.tensor([0.485, 0.456, 0.406], dtype=torch.float32).view(3, 1, 1)
IMAGENET_STD = torch.tensor([0.229, 0.224, 0.225], dtype=torch.float32).view(3, 1, 1)
INPUT_MODE_FIXED = "fixed"
INPUT_MODE_RECT_DYNAMIC = "rect_dynamic"
INPUT_MODES = {INPUT_MODE_FIXED, INPUT_MODE_RECT_DYNAMIC}

BBox = Tuple[float, float, float, float]


def _load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def resolve_path(path_value: Optional[str], *, index_path: Path, dataset_root: Optional[Path]) -> Optional[Path]:
    if path_value is None:
        return None

    raw = Path(path_value)
    candidates: List[Path] = []
    if raw.is_absolute():
        candidates.append(raw)
    else:
        if dataset_root is not None:
            candidates.append(dataset_root / raw)
            candidates.append(dataset_root / raw.name)
        candidates.append(Path.cwd() / raw)
        candidates.append(index_path.parent / raw)
        candidates.append(index_path.parent / raw.name)

    for candidate in candidates:
        if candidate.exists():
            return candidate

    return candidates[0] if candidates else raw


def infer_input_mode(samples: Sequence[Dict[str, Any]]) -> str:
    if not samples:
        return INPUT_MODE_FIXED
    mode = str(samples[0].get("input_mode", INPUT_MODE_FIXED))
    return mode if mode in INPUT_MODES else INPUT_MODE_FIXED


def clip_bbox_to_image(box: Sequence[float], image_size: Tuple[int, int]) -> Optional[BBox]:
    width, height = image_size
    if len(box) != 4:
        return None
    x1, y1, x2, y2 = [float(v) for v in box]
    left = max(0, min(width, int(math.floor(x1))))
    top = max(0, min(height, int(math.floor(y1))))
    right = max(0, min(width, int(math.ceil(x2))))
    bottom = max(0, min(height, int(math.ceil(y2))))
    if right <= left or bottom <= top:
        return None
    return float(left), float(top), float(right), float(bottom)


def full_to_rect_crop(points: np.ndarray, crop_box: BBox) -> np.ndarray:
    x1, y1, _, _ = crop_box
    out = np.empty_like(points, dtype=np.float32)
    out[:, 0] = points[:, 0] - x1
    out[:, 1] = points[:, 1] - y1
    return out


def make_dynamic_heatmaps(
    corners_crop: np.ndarray,
    corner_visible: Sequence[int],
    crop_hw: Tuple[int, int],
    sigma: float,
    output_stride: int = 4,
) -> Tuple[np.ndarray, List[int]]:
    crop_h, crop_w = crop_hw
    heat_h = max(1, int(math.ceil(crop_h / float(output_stride))))
    heat_w = max(1, int(math.ceil(crop_w / float(output_stride))))
    heatmaps = np.zeros((8, heat_h, heat_w), dtype=np.float32)
    valid: List[int] = []
    yy, xx = np.mgrid[0:heat_h, 0:heat_w].astype(np.float32)
    scale_x = heat_w / float(max(1, crop_w))
    scale_y = heat_h / float(max(1, crop_h))

    for idx, point in enumerate(corners_crop):
        x_hm = float(point[0] * scale_x)
        y_hm = float(point[1] * scale_y)
        is_valid = bool(corner_visible[idx]) and 0 <= point[0] < crop_w and 0 <= point[1] < crop_h and 0 <= x_hm < heat_w and 0 <= y_hm < heat_h
        valid.append(1 if is_valid else 0)
        if not is_valid:
            continue
        heatmaps[idx] = np.exp(-((xx - x_hm) ** 2 + (yy - y_hm) ** 2) / (2.0 * sigma**2))

    return heatmaps, valid


class BOPCornerDataset(Dataset):
    """Dataset for MyNet JSON files generated by scripts/build_mynet_dataset.py."""

    def __init__(
        self,
        index_path: str | Path,
        dataset_root: str | Path | None = None,
        normalize: bool = True,
        input_mode: str = "auto",
        heatmap_sigma: float = 2.0,
    ) -> None:
        self.index_path = Path(index_path)
        self.dataset_root = Path(dataset_root) if dataset_root is not None else None
        self.samples: List[Dict[str, Any]] = _load_json(self.index_path)
        self.normalize = normalize
        self.heatmap_sigma = heatmap_sigma

        if not isinstance(self.samples, list):
            raise ValueError(f"Index must contain a list of samples: {self.index_path}")
        self.input_mode = infer_input_mode(self.samples) if input_mode == "auto" else input_mode
        if self.input_mode not in INPUT_MODES:
            raise ValueError(f"Unsupported input mode: {self.input_mode}")

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        sample = self.samples[idx]
        if str(sample.get("input_mode", self.input_mode)) == INPUT_MODE_RECT_DYNAMIC or self.input_mode == INPUT_MODE_RECT_DYNAMIC:
            return self._getitem_rect_dynamic(sample, idx)

        crop_path = resolve_path(sample["crop_path"], index_path=self.index_path, dataset_root=self.dataset_root)
        heatmap_path = resolve_path(sample["heatmap_path"], index_path=self.index_path, dataset_root=self.dataset_root)
        if crop_path is None or heatmap_path is None:
            raise FileNotFoundError(f"Missing crop or heatmap path for sample {sample.get('sample_id', idx)}")

        image_np = np.asarray(Image.open(crop_path).convert("RGB"), dtype=np.float32) / 255.0
        image = torch.from_numpy(image_np).permute(2, 0, 1).contiguous()
        if self.normalize:
            image = (image - IMAGENET_MEAN) / IMAGENET_STD

        heatmap_np = np.load(heatmap_path).astype(np.float32)
        heatmap = torch.from_numpy(heatmap_np)

        return {
            "image": image,
            "heatmap": heatmap,
            "corners_2d_crop": torch.tensor(sample["corners_2d_crop"], dtype=torch.float32),
            "corner_valid": torch.tensor(sample["corner_valid"], dtype=torch.bool),
            "crop_box_xyxy_full": torch.tensor(sample["crop_box_xyxy_full"], dtype=torch.float32),
            "K": torch.tensor(sample["K"], dtype=torch.float32),
            "R": torch.tensor(sample["R"], dtype=torch.float32),
            "t": torch.tensor(sample["t"], dtype=torch.float32),
            "sample_id": sample["sample_id"],
            "input_mode": INPUT_MODE_FIXED,
        }

    def _getitem_rect_dynamic(self, sample: Dict[str, Any], idx: int) -> Dict[str, Any]:
        rgb_path = resolve_path(sample.get("rgb_path"), index_path=self.index_path, dataset_root=self.dataset_root)
        if rgb_path is None:
            raise FileNotFoundError(f"Missing rgb path for sample {sample.get('sample_id', idx)}")

        image_full = Image.open(rgb_path).convert("RGB")
        crop_box = clip_bbox_to_image(sample["bbox_xyxy_full"], image_full.size)
        if crop_box is None:
            raise ValueError(f"Invalid rect_dynamic bbox for sample {sample.get('sample_id', idx)}: {sample.get('bbox_xyxy_full')}")

        left, top, right, bottom = [int(v) for v in crop_box]
        crop = image_full.crop((left, top, right, bottom))
        crop_w, crop_h = crop.size
        image_np = np.asarray(crop, dtype=np.float32) / 255.0
        image = torch.from_numpy(image_np).permute(2, 0, 1).contiguous()
        if self.normalize:
            image = (image - IMAGENET_MEAN) / IMAGENET_STD

        corners_full = np.asarray(sample["corners_2d_full"], dtype=np.float32)
        corners_crop = full_to_rect_crop(corners_full, crop_box)
        corner_visible = [int(v) for v in sample.get("corner_visible", [1] * 8)]
        heatmaps, corner_valid = make_dynamic_heatmaps(corners_crop, corner_visible, (crop_h, crop_w), sigma=self.heatmap_sigma)

        return {
            "image": image,
            "heatmap": torch.from_numpy(heatmaps),
            "corners_2d_crop": torch.tensor(corners_crop, dtype=torch.float32),
            "corner_valid": torch.tensor(corner_valid, dtype=torch.bool),
            "crop_box_xyxy_full": torch.tensor(crop_box, dtype=torch.float32),
            "crop_hw": torch.tensor([crop_h, crop_w], dtype=torch.float32),
            "K": torch.tensor(sample["K"], dtype=torch.float32),
            "R": torch.tensor(sample["R"], dtype=torch.float32),
            "t": torch.tensor(sample["t"], dtype=torch.float32),
            "sample_id": sample["sample_id"],
            "input_mode": INPUT_MODE_RECT_DYNAMIC,
        }


def collate_corner_batch(batch: List[Dict[str, Any]]) -> Dict[str, Any]:
    tensor_keys = [
        "image",
        "heatmap",
        "corners_2d_crop",
        "corner_valid",
        "crop_box_xyxy_full",
        "K",
        "R",
        "t",
    ]
    if "crop_hw" in batch[0]:
        tensor_keys.append("crop_hw")
    if len(batch) > 1:
        image_shapes = {tuple(item["image"].shape) for item in batch}
        heatmap_shapes = {tuple(item["heatmap"].shape) for item in batch}
        if len(image_shapes) > 1 or len(heatmap_shapes) > 1:
            raise ValueError("rect_dynamic samples are strict variable-size tensors; use batch_size=1 with gradient accumulation.")
    out: Dict[str, Any] = {key: torch.stack([item[key] for item in batch], dim=0) for key in tensor_keys}
    out["sample_id"] = [item["sample_id"] for item in batch]
    out["input_mode"] = [item.get("input_mode", INPUT_MODE_FIXED) for item in batch]
    return out
